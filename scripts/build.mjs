import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import vm from 'node:vm';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = path.join(root, 'src');
const read = name => readFile(path.join(sourceDir, name), 'utf8');
const version = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8')).version;
if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error('package.json version must be plain semver (X.Y.Z), got ' + version);
/** The one place a version is written by hand is package.json; everything else is generated from it. */
const changelogRow = (await readFile(path.join(root, 'CHANGELOG.md'), 'utf8')).match(new RegExp(`^\\| ${version.replace(/\./g, '\\.')} \\| ([^|]+)\\| ([^|]+) \\|`, 'm'));
const versionNote = changelogRow ? `${changelogRow[1].trim()} - ${changelogRow[2].trim().replace(/\*\//g, '')}` : 'no CHANGELOG.md entry yet';
const versionSource = `/**\n * TAK v${version} (${versionNote})\n * Full history: CHANGELOG.md in the repository.\n * Generated by scripts/build.mjs from package.json. Do not edit.\n */\nvar TAK_APP_VERSION = '${version}';\nfunction takAppVersion_() { return '${version}'; }\n`;
await writeFile(path.join(sourceDir, 'Version.js'), versionSource);
new vm.Script(versionSource, { filename: 'Version.js' });
const core = await read('Core.js');
new vm.Script(core, { filename: 'Core.js' });
new vm.Script(await read('Code.js'), { filename: 'Code.js' });
new vm.Script(await read('PersonalBatch.js'), { filename: 'PersonalBatch.js' });
new vm.Script(await read('Schema.js'), { filename: 'Schema.js' });
new vm.Script(await read('Migrations.js'), { filename: 'Migrations.js' });
new vm.Script(await read('Environment.js'), { filename: 'Environment.js' });
new vm.Script(await read('Repository.js'), { filename: 'Repository.js' });
new vm.Script(await read('History.js'), { filename: 'History.js' });
new vm.Script(await read('Authorization.js'), { filename: 'Authorization.js' });
new vm.Script(await read('Settings.js'), { filename: 'Settings.js' });
new vm.Script(await read('Ordering.js'), { filename: 'Ordering.js' });
new vm.Script(await read('Comments.js'), { filename: 'Comments.js' });
new vm.Script(await read('SharedHost.js'), { filename: 'SharedHost.js' });
new vm.Script(await read('Roadmap.js'), { filename: 'Roadmap.js' });
const claspIgnore = await readFile(path.join(root, '.claspignore'), 'utf8');
if (!claspIgnore.includes('!Roadmap.js')) throw new Error('Roadmap.js must be included in the Apps Script deployment allowlist.');
if (!claspIgnore.includes('!Version.js')) throw new Error('Version.js must be included in the Apps Script deployment allowlist.');
for (const name of ['QuickAdd', 'Help', 'FullScreen']) {
  const file = name + '.html';
  for (const match of (await read(file)).matchAll(/<script>([\s\S]*?)<\/script>/g)) new vm.Script(match[1], { filename: file });
  if (!claspIgnore.includes('!' + file)) throw new Error(file + ' must be included in the Apps Script deployment allowlist.');
}
const browserCore = `<script>\n${core}\n</script>\n`;
await writeFile(path.join(sourceDir, 'CoreScript.html'), browserCore);
let html = await read('Index.html');
for (const name of ['Styles', 'CoreScript', 'Client']) {
  const content = name === 'CoreScript' ? browserCore : await read(name + '.html');
  html = html.replace(`<?!= include_('${name}'); ?>`, () => content);
}
html = html.replaceAll('<?= takAppVersion_() ?>', version);
html = html.replace('<?= initialView ?>', 'kanban');
html = html.replace('<?= sharedSheetId ?>', '');
html = html.replace('<?= oauthToken ?>', '');
html = html.replace('<?= pickerAppId ?>', '');
html = html.replace('<?= pickerApiKey ?>', '');
html = html.replace(/\s*<script src="https:\/\/apis\.google\.com\/js\/api\.js" async defer><\/script>/, '');
html = html.replace(/[ \t]+(?=\r?\n)/g, '');
for (const match of html.matchAll(/<script>([\s\S]*?)<\/script>/g)) new vm.Script(match[1], { filename: 'browser-script' });
if (html.includes('<?')) throw new Error('Unresolved Apps Script template');
await mkdir(path.join(root, 'dist'), { recursive: true });
await writeFile(path.join(root, 'dist', 'index.html'), html);
console.log(`Built TAK v${version}: dist/index.html, src/CoreScript.html and src/Version.js. No external assets or runtime dependencies.`);
